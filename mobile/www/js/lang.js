let currentLanguage = localStorage.getItem('rubra_lang') || 'en';

function t(key, variables = {}) {
    const lang = currentLanguage;
    let translation = translations[lang] && translations[lang][key] ? translations[lang][key] : (translations['en'][key] || key);
    for (const [k, v] of Object.entries(variables)) {
        translation = translation.replace(`{${k}}`, v);
    }
    return translation;
}

function setLanguage(lang) {
    if (lang !== 'en' && lang !== 'az') lang = 'en';
    currentLanguage = lang;
    localStorage.setItem('rubra_lang', lang);

    // Sync selector values
    const selectLanguage = document.getElementById('select-language');
    const prefLang = document.getElementById('pref-lang');
    if (selectLanguage) selectLanguage.value = lang;
    if (prefLang) prefLang.value = lang;

    // Update all HTML elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (el.tagName === 'INPUT' && (el.type === 'text' || el.type === 'email' || el.type === 'password')) {
            el.placeholder = t(key);
        } else {
            el.innerHTML = t(key);
        }
    });

    // Refresh UI dashboards
    if (typeof updateCycleDashboard === 'function') updateCycleDashboard();
    if (typeof renderHistory === 'function') renderHistory();
    if (typeof renderLogCalendar === 'function') renderLogCalendar();
}
